// bookEnvNamesPath is the user guide's table of every variable name snug has
// a type for.
const bookEnvNamesPath = "../../docs/src/reference/environment-names.md"

// TestBookEnvironmentNamesPageIsGenerated renders the roster (envTypes), the
// owned names (SnugOwnedEnv) and the feature-conditional names
// (conditionalEnvs) into docs/src/reference/environment-names.md.
//
// The verbs column is not read off envType's fields: it is checkEnvEntry's
// verdict for each verb, the same call a profile's environ block goes through,
// so the page cannot claim a verb the parser refuses. Regenerate with
//
//	go test ./internal/policy -run TestBookEnvironmentNamesPageIsGenerated -update
func TestBookEnvironmentNamesPageIsGenerated(t *testing.T) {
	verbs := []EnvVerb{VerbSet, VerbMerge, VerbPrepend, VerbInherit, VerbSanitise}
	empty := map[emptyKind]string{
		emptyNA:       "",
		emptyIgnored:  "ignored",
		emptyCWD:      "current directory",
		emptyOperator: "inserts the default",
		emptySystem:   "system location",
	}

	var b strings.Builder
	b.WriteString("<!-- GENERATED by TestBookEnvironmentNamesPageIsGenerated\n" +
		"     (internal/policy/bookenvnames_test.go) from envTypes, SnugOwnedEnv and conditionalEnvs.\n" +
		"     Do not edit; regenerate with -update. -->\n\n")
	b.WriteString("# Environment names\n\n")
	b.WriteString("Every variable name snug has a type for, and the verbs a profile may use on it.\n")
	b.WriteString("A name not listed here takes `set` and `inherit`, or the verbs of the type a profile declares for it\n" +
		"in `environ.types`. See [Environment](../environment.md#declaring-a-type).\n\n")
	b.WriteString("**path**: every element must be granted by the profile that writes it.\n")
	b.WriteString("**empty element**: what the program reading the variable does with one.\n\n")
	b.WriteString("| name | kind | separator | empty element | path | verbs |\n")
	b.WriteString("|---|---|---|---|---|---|\n")

	names := make([]string, 0, len(envTypes))
	for n := range envTypes {
		names = append(names, n)
	}
	slices.Sort(names)
	for _, n := range names {
		ty := envTypes[n]
		kind, sep, path := "scalar", "", ""
		if ty.list {
			kind = "list"
			sep = bookSep(ty.sep)
			if ty.altSep != "" {
				sep += " or " + bookSep(ty.altSep)
			}
		}
		if ty.path {
			path = "yes"
		}
		var ok []string
		for _, v := range verbs {
			if checkEnvEntry(n, v, nil) == nil {
				ok = append(ok, "`"+v.String()+"`")
			}
		}
		allowed := strings.Join(ok, " ")
		if allowed == "" {
			allowed = "none"
		}
		b.WriteString("| `" + n + "` | " + kind + " | " + sep + " | " + empty[ty.empty] +
			" | " + path + " | " + allowed + " |\n")
	}

	b.WriteString("\n## Names snug writes\n\n")
	b.WriteString("No profile may `set`, `inherit` or declare these, in any run, whether or not snug writes\n" +
		"the name in that run. `PATH` is a list and still takes `merge` and `prepend`.\n\n")
	b.WriteString("| snug writes it | names |\n|---|---|\n")
	grouped := map[string]bool{}
	for _, g := range bookOwnedGroups {
		names := slices.Clone(g.names)
		slices.Sort(names)
		var cells []string
		for _, n := range names {
			if !slices.Contains(SnugOwnedEnv, n) {
				t.Errorf("bookOwnedGroups lists %s, which is not in SnugOwnedEnv", n)
			}
			grouped[n] = true
			cells = append(cells, "`"+n+"`")
		}
		b.WriteString("| " + g.when + " | " + strings.Join(cells, " ") + " |\n")
	}
	for _, n := range SnugOwnedEnv {
		if !grouped[n] {
			t.Errorf("SnugOwnedEnv has %s and bookOwnedGroups does not say when snug writes it", n)
		}
	}

	b.WriteString("\n## Names snug writes when a feature is on\n\n")
	b.WriteString("In a selection that turns the feature on, a profile line on one of these names is refused.\n" +
		"The refusal names that profile, and the profile and key that turned the feature on. With the\n" +
		"feature off, a profile may write them. No profile may declare them in `environ.types`, and no\n" +
		"built-in profile writes them. **also claimed** names are ones snug does not write, but the tool\n" +
		"reads them in place of what snug wrote.\n\n")
	b.WriteString("| feature on when | snug writes | also claimed |\n|---|---|---|\n")
	seen := map[string]bool{}
	for _, c := range conditionalEnvs {
		when, ok := bookConditionalWhen[c.names[0]]
		if !ok {
			t.Errorf("conditionalEnvs has a feature writing %s and bookConditionalWhen does not say when it is on", c.names[0])
		}
		seen[c.names[0]] = true
		b.WriteString("| " + when + " | " + bookCodeList(c.names) + " | " + bookCodeList(c.outranks) + " |\n")
	}
	for k := range bookConditionalWhen {
		if !seen[k] {
			t.Errorf("bookConditionalWhen has %s, which starts no feature in conditionalEnvs", k)
		}
	}
	got := b.String()

	if *update {
		if err := os.WriteFile(bookEnvNamesPath, []byte(got), 0o644); err != nil {
			t.Fatal(err)
		}
		return
	}
	want, err := os.ReadFile(bookEnvNamesPath)
	if err != nil {
		t.Fatalf("%v\n  generate it: go test ./internal/policy -run TestBookEnvironmentNamesPageIsGenerated -update", err)
	}
	if string(want) != got {
		t.Errorf("%s is stale: the environment roster changed and the page did not.\n"+
			"  regenerate: go test ./internal/policy -run TestBookEnvironmentNamesPageIsGenerated -update",
			bookEnvNamesPath)
	}
}

// bookCodeList renders names sorted, each in backticks.
func bookCodeList(names []string) string {
	sorted := slices.Clone(names)
	slices.Sort(sorted)
	cells := make([]string, 0, len(sorted))
	for _, n := range sorted {
		cells = append(cells, "`"+n+"`")
	}
	return strings.Join(cells, " ")
}

// bookSep renders a separator so a space is readable in a table cell.
func bookSep(s string) string {
	if s == " " {
		return "space"
	}
	return "`" + s + "`"
}

// bookOwnedGroups says WHEN snug writes each owned name, for the book. The
// test above fails unless the groups cover SnugOwnedEnv exactly, so a name
// added to or removed from the owned set cannot miss this table; the
// condition text is prose and is checked by review.
var bookOwnedGroups = []struct {
	when  string
	names []string
}{
	{"every run", []string{"HOME", "PATH", "SHELL", "USER", "LOGNAME", "TMPDIR", "PS1",
		"SNUG", "SNUG_PROFILES", "SNUG_TARGET"}},
	{"when the host has a value", []string{"TERM", "LANG", "TZ"}},
}

// bookConditionalWhen says, for the book, which selection turns on each
// feature in conditionalEnvs, keyed by the feature's first name. The test
// fails unless every feature has a row and every row a feature; the text is
// prose over conditionalEnv.on and is checked by review.
var bookConditionalWhen = map[string]string{
	"CONTAINER_HOST":    "`podman` is `\"socket\"` or `\"build\"`",
	"SSH_AUTH_SOCK":     "`identity.ssh.agent` is `\"proxy\"`",
	"GH_CONFIG_DIR":     "`identity.gh.user` is set",
	"GIT_CONFIG_GLOBAL": "an `identity.ssh` or `identity.git` block",
	"KUBECONFIG":        "an `identity.kube` block",
	"LISTEN_FDNAMES":    "`listen_names` is set",
	"BROWSER":           "`login` includes `\"claude\"`",
}
