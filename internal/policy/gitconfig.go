// GitConfigFrom renders the generated ~/.gitconfig for an [identity] block, or
// nil when id is nil.
//
// The file is AUTHORED, never carried from the host. ~/.gitconfig is not a data
// file with a name and an email in it — it is a COMMAND TABLE:
// `credential.helper`, `alias.x = !cmd`, `core.pager`, `core.sshCommand`,
// `diff.*.textconv`, `filter.*.clean/smudge` and `core.fsmonitor` all name
// programs for git to run. Binding it read-only does not stop any of that; it
// SUPPLIES it. So the only inputs are the values the profile pinned.
//
// home is the sandbox's HOME, needed because user.signingkey must be an
// absolute guest path: git does not expand `~` there, and a relative value would
// resolve against whatever directory the payload happens to be in.
//
// Signing is authored, not configurable beyond the pin. user.signingkey names
// the staged guest copy of the key, because a path on the HOST does not exist
// inside, and a `commit.gpgsign = true` over a key nobody can sign with turns
// every commit into `error: No private key found for public key "…"` followed
// by `fatal: failed to write commit object` (measured, git 2.55.0) — worse than
// an unsigned commit. snug therefore authors the signing block only for a key it
// has staged, whose identity.ssh.agent = "proxy" the resolver has already
// required, and which sshproxy.New has already asked the host agent to SIGN with
// once. Presence was not enough: a key added with `ssh-add -c` and no askpass,
// or with `ssh-add -h <destination>`, is LISTED by the agent and refused at
// every signature — measured, and it is the setup a careful person has, since a
// signing key is frequently the one key in the agent that is authorised to push
// nowhere.
//
// Two residuals this comment cannot close, both measured. A repo-local
// `.git/config` with `commit.gpgsign = true` arrives inside regardless — the
// target is bound and GIT_CONFIG_GLOBAL displaces only the GLOBAL file — so a
// signed commit from inside a repo that asks for a key snug did not stage fails
// with the agent proxy's refusal, `agent refused operation`, which reads as a
// host keyring fault. And the agent protocol carries no purpose, so pinning a
// second key for signing means either key can be used for either purpose by
// anything inside.
func GitConfigFrom(id *Identity, home string) []byte {
	if id == nil {
		return nil
	}
	// Belt and braces, the same shape as withoutControlCharacters: Resolve has
	// already refused signing_key with agent = none, and this is the backstop
	// for whatever calls the renderer next.
	sshSigning := id.Git.SigningKey != "" && id.SSH.Agent != SSHNone
	// GPG commit signing, on exactly the same footing as the ssh arm above: a
	// key served by an agent the resolver has already required, and which
	// gpgproxy.New has already asked the host agent to SIGN with once before
	// the listener was bound. The SCOPE is what decides it — a pin scoped only
	// "decrypt" must NOT turn commit signing on, or a decryption grant would
	// silently be a signing oracle for the same key. `gpg.format` is one value,
	// so the two arms cannot both write it; Resolve refuses that combination
	// (refuseTwoSigningKeys) rather than picking a winner here.
	gpgSigning := id.GPG.Fingerprint != "" && GPGScopeHas(id.GPG.Scope, GPGScopeSign)
	signing := sshSigning || gpgSigning
	// Second guard, deliberately not the only one. The identity block is
	// validated at load, and this is the backstop for whatever calls the renderer
	// next — because the failure it prevents is not cosmetic: a newline inside
	// `user.name` closes the `name = …` line and opens a real `[alias] x = !cmd`
	// section in the file the sandbox trusts. Measured by the red team, with the
	// injected alias executing inside the sandbox. Rendering is the last place
	// this can be caught, so it is caught here too.
	name := withoutControlCharacters(id.Git.Name)
	email := withoutControlCharacters(id.Git.Email)

	var b strings.Builder
	b.WriteString("# Generated by snug from the profile's [identity] pin. The host's git config\n")
	b.WriteString("# is not mounted: it names programs to run (credential.helper, alias = !cmd,\n")
	b.WriteString("# core.pager, textconv), and a read-only bind supplies those rather than\n")
	b.WriteString("# stopping them.\n")
	if name != "" || email != "" || signing {
		b.WriteString("[user]\n")
		if name != "" {
			fmt.Fprintf(&b, "\tname = %s\n", gitQuote(name))
		}
		if email != "" {
			fmt.Fprintf(&b, "\temail = %s\n", gitQuote(email))
		}
		if sshSigning {
			fmt.Fprintf(&b, "\tsigningkey = %s\n", gitQuote(home+"/"+SigningKeyGuest))
		}
		if gpgSigning {
			// The FINGERPRINT, not a path: git's openpgp backend hands this to
			// gpg, which matches the key inside the agent by fingerprint. The
			// sandbox reads no key file for it, so there is nothing to stage for
			// this value — the public keyring is staged by internal/cli.
			fmt.Fprintf(&b, "\tsigningkey = %s\n", gitQuote(id.GPG.Fingerprint))
		}
	}
	if sshSigning {
		b.WriteString("# AUTHORED from identity.git.signing_key: the private half stays in the\n")
		b.WriteString("# host agent and only the .pub is inside.\n")
		b.WriteString("# gpgsign is true because snug asked your host agent for one signature with\n")
		b.WriteString("# this key at startup and got one. A key the agent merely LISTS can still\n")
		b.WriteString("# refuse every signature (ssh-add -c with no askpass, ssh-add -h), which\n")
		b.WriteString("# would fail every commit here with an error naming no cause.\n")
		b.WriteString("[gpg]\n\tformat = ssh\n")
		// Without allowedSignersFile every `%G` placeholder and
		// `git log --show-signature` fails VERIFICATION rather than signing, and
		// the sharp shape is that --show-signature prints "No signature" and
		// exits 0 — a signed commit reading as unsigned, successfully (#576).
		// snug AUTHORS the file from the same two values it already holds, so
		// the run verifies the key the profile pinned and nothing else.
		fmt.Fprintf(&b, "[gpg \"ssh\"]\n\tallowedSignersFile = %s\n",
			gitQuote(home+"/"+AllowedSignersGuest))
		b.WriteString("[commit]\n\tgpgsign = true\n")
	}
	if gpgSigning {
		b.WriteString("# AUTHORED from identity.gpg: the private half stays in the host agent and\n")
		b.WriteString("# the sandbox's ~/.gnupg holds only the public keyring, whose S.gpg-agent\n")
		b.WriteString("# is snug's filtering proxy.\n")
		b.WriteString("# gpgsign is true because snug asked your host agent for one signature with\n")
		b.WriteString("# this key at startup and got one. A key the agent merely LISTS can still\n")
		b.WriteString("# refuse every signature (a pinentry prompt with no tty, a smartcard that\n")
		b.WriteString("# is not inserted), which would fail every commit here naming no cause.\n")
		b.WriteString("[gpg]\n\tformat = openpgp\n")
		// No allowedSignersFile: that is the ssh backend's verifier list. The
		// openpgp backend verifies against gpg's keyring, and the sandbox's
		// keyring holds exactly the pinned key (staged by internal/cli), so a run
		// verifies the key the profile pinned and nothing else.
		b.WriteString("[commit]\n\tgpgsign = true\n")
	}
	if id.SSH.Agent != SSHNone {
		host := id.SSHHost()
		fmt.Fprintf(&b, "[url \"git@%s:\"]\n\tinsteadOf = https://%s/\n", host, host)
	}
	b.WriteString("[safe]\n\tdirectory = *\n")
	return []byte(b.String())
}

// gitQuote renders a value the way git's own writer does: always quoted, with
// `\` and `"` escaped.
//
// Dropping control characters was only half of it. git's config VALUE syntax has
// four more characters that change meaning, and writing values raw got every one
// of them wrong — measured, host value in, sandbox value out:
//
//	A " B        ->  name = A " B        ->  fatal: bad config line 2
//	Bob # Smith  ->  name = Bob # Smith  ->  Bob        (comment)
//	Bob ; Smith  ->  name = Bob ; Smith  ->  Bob        (comment)
//	"  Bob"      ->  name =   Bob        ->  Bob        (leading space eaten)
//	C:\temp      ->  name = C:\temp      ->  C:<TAB>emp (escape re-read)
//
// The quote case is the sharp one, and it is a total failure rather than a
// cosmetic one: GIT_CONFIG_GLOBAL points at the generated file, so a `"` in
// user.name makes `git version` itself die inside the sandbox, naming a
// file the human never wrote. Quoting is the fix; adding more characters to the
// drop list is not, because a name legitimately containing `"` is a person's
// name and not an attack.
func gitQuote(v string) string {
	var b strings.Builder
	b.WriteByte('"')
	for i := 0; i < len(v); i++ {
		switch c := v[i]; c {
		case '\\', '"':
			b.WriteByte('\\')
			b.WriteByte(c)
		default:
			b.WriteByte(c)
		}
	}
	b.WriteByte('"')
	return b.String()
}

// withoutControlCharacters returns "" for a value that could author a directive
// rather than be one. A name and an email address have no use for a control
// character, so there is nothing to weigh: the value goes.
//
// THE ASCII SCOPE IS DELIBERATE AND IS NOT THE SCREEN'S SCOPE. This filter and
// IsForgingRune answer two different questions, and a reader arriving from the
// widened screen guard will want to widen this one out of symmetry. Do not.
//
//   - THIS one asks: can the rune author a DIRECTIVE in the file snug writes?
//     git's config parser terminates a value at a NEWLINE and starts a section
//     at a `[` in column one; nothing else in the grammar is a terminator.
//     U+0085, U+2028 and U+202E are ordinary bytes to it — measured shape, and
//     the same reason `gitQuote` handles `"`, `#`, `;` and `\` rather than this
//     function. So C0 and DEL already cover every rune that can end a line, and
//     the extra ones a wider predicate would add close nothing here.
//   - THE SCREEN asks: can the rune make a rendered line read as something snug
//     did not write? That is IsForgingRune, and it IS wider — but its remedy is
//     to ESCAPE at the sink (policy.VisibleText), not to drop the value.
//
// The difference matters because THIS function's remedy is a DROP, and a drop is
// a downgrade: a user.name legitimately carrying a directional isolate — a
// mixed-direction personal name is the normal case for one, not an attack — would
// leave the sandbox with no git identity and `git commit` failing. Widening a
// filter whose remedy is "the value goes" costs a working sandbox; widening a
// guard whose remedy is "the value is escaped" costs nothing.
func withoutControlCharacters(v string) string {
	if strings.IndexFunc(v, func(r rune) bool { return r < 0x20 || r == 0x7f }) >= 0 {
		return ""
	}
	return v
}
