// TestBwrapAtDestinationMirrorsTheMeasuredTable is the table in one place, and
// it is the reason ARM 3 is a lookup rather than an IsRegular test. Every row
// was RUN on bubblewrap 0.12.0 — `bwrap --dev-bind / / <cover> $g $g <flag> 9
// $g/<shape> -- true 9<content`, with the host tree read afterwards — and the
// two rows nobody would have guessed are the ones that make the difference:
// --ro-bind-data MOUNTS over a FIFO and over a socket, writing nothing, so
// refusing them would deny a policy bubblewrap runs.
func TestBwrapAtDestinationMirrorsTheMeasuredTable(t *testing.T) {
	const dest = "/srv/app/gen.conf"
	file := func(mode fs.FileMode) fs.FileInfo { return fakeInfo{name: dest, mode: mode} }

	for _, tc := range []struct {
		name          string
		fi            fs.FileInfo
		access        Access
		coverWritable bool
		said, writes  string
	}{
		// Every row here has the destination's parent directory PRESENT; the
		// missing-parent rows are their own table below, because bwrap says
		// "Can't mkdir parents for …" there and creates directories as well as
		// the file.
		{"regular file, ro mount, ro cover", file(0), AccessRO, false, "", ""},
		{"regular file, ro mount, rw cover", file(0), AccessRO, true, "", ""},
		{"regular file, rw mount, rw cover", file(0), AccessRW, true, "", "overwrites"},
		{"regular file, rw mount, ro cover", file(0), AccessRW, false,
			"bwrap: Can't create file " + dest + ": Read-only file system", ""},

		{"absent, ro mount, rw cover", nil, AccessRO, true, "", "creates"},
		{"absent, rw mount, rw cover", nil, AccessRW, true, "", "creates"},
		{"absent, ro mount, ro cover", nil, AccessRO, false,
			"bwrap: Can't create file " + dest + ": Read-only file system", ""},

		{"symlink, ro mount", file(fs.ModeSymlink), AccessRO, false,
			"bwrap: Can't mount on symlink destination " + dest, ""},
		{"symlink, rw mount", file(fs.ModeSymlink), AccessRW, true,
			"bwrap: Can't create file " + dest + ": Too many levels of symbolic links", ""},

		{"directory, ro mount", file(fs.ModeDir), AccessRO, false,
			"bwrap: Destination is not a file " + dest, ""},
		{"directory, rw mount", file(fs.ModeDir), AccessRW, true,
			"bwrap: Can't create file " + dest + ": Is a directory", ""},

		// The two acceptances that are not regular files.
		{"FIFO, ro mount", file(fs.ModeNamedPipe), AccessRO, false, "", ""},
		{"socket, ro mount", file(fs.ModeSocket), AccessRO, false, "", ""},

		{"socket, rw mount", file(fs.ModeSocket), AccessRW, true,
			"bwrap: Can't create file " + dest + ": No such device or address", ""},
	} {
		t.Run(tc.name, func(t *testing.T) {
			v := bwrapAtDestination(dest, tc.fi, true, tc.access, tc.coverWritable)
			if v.said != tc.said {
				t.Errorf("said = %q, measured %q", v.said, tc.said)
			}
			if v.writes != tc.writes {
				t.Errorf("writes = %q, measured %q", v.writes, tc.writes)
			}
			if got := v.ok(); got != (tc.said == "" && tc.writes == "") {
				t.Errorf("ok() = %v, which disagrees with the row itself", got)
			}
		})
	}

	// The FIFO row for a WRITABLE mount is its own case because bwrap gives no
	// message at all: --file opens the destination, opening a FIFO with no
	// reader blocks, and the run never returns. Measured with `timeout 10`,
	// which is what killed it (rc 124). The refusal says so rather than quoting
	// a sentence that does not exist.
	v := bwrapAtDestination(dest, file(fs.ModeNamedPipe), true, AccessRW, true)
	if v.ok() {
		t.Fatal("accepted a writable generated file onto a FIFO; bwrap blocks in the open and " +
			"the run hangs with nothing printed")
	}
	if !strings.Contains(v.said, "blocks") || strings.Contains(v.said, "Can't create file") {
		t.Errorf("the FIFO verdict quotes a bwrap sentence instead of saying it hangs: %q", v.said)
	}
}

