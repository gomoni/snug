const probeFileBody = "[user]\n\tname = {profile.probeid.identity.git.name}\n[x]\n\thome = {home}\n\tbrace = {lbrace}ok{rbrace}\n\tlast = no newline"

func probeFileRegistry(t *testing.T) map[policy.ProfileName]*policy.Profile {
	t.Helper()
	reg, err := profile.Builtins()
	if err != nil {
		t.Fatal(err)
	}
	out := map[policy.ProfileName]*policy.Profile(reg)
	out["probeid"] = &policy.Profile{Name: "probeid", Identity: &policy.Identity{
		Git: policy.IdentityGit{Name: "Probe Person", Email: "probe@example.com"}}}
	out["probefile"] = &policy.Profile{Name: "probefile", Include: []policy.ProfileName{"probeid"},
		File: []policy.FileGrant{{Path: "{home}/.config/probe.conf", Content: probeFileBody}}}
	return out
}

func probeFilePolicy(t *testing.T, sel ...policy.ProfileName) *policy.Policy {
	t.Helper()
	p, err := policy.Resolve(probeFileRegistry(t), sel, envGoldenCtx(), newEnvFakeEnv())
	if err != nil {
		t.Fatalf("Resolve(%v): %v", sel, err)
	}
	return p
}

func probeFileSelection() []policy.ProfileName {
	return append(append([]policy.ProfileName{}, profile.BuiltinDefaults()...), "probefile")
}

func TestGoldenProfileFileFilesystem(t *testing.T) {
	p := probeFilePolicy(t, probeFileSelection()...)
	screen := dryRunText(p, []string{"/bin/sh"}, config{}, nil)
	got := strings.TrimRight(blockBetween(t, screen, "FILESYSTEM", "NOT GRANTED"), " \n") + "\n\n" +
		strings.TrimRight(blockBetween(t, screen, "FILES  (", "ENVIRONMENT"), " \n") + "\n"
	goldenText(t, "filesystem.profile-file.txt", got)
}

func TestGoldenProfileFileJSON(t *testing.T) {
	p := probeFilePolicy(t, probeFileSelection()...)
	var buf bytes.Buffer
	rep := buildReport(newEnvFakeEnv(), p, p.BwrapArgs(0, 0), config{json: true}, nil, nil)
	rep.Seccomp = jsonGoldenSeccomp
	if err := renderJSON(&buf, rep); err != nil {
		t.Fatal(err)
	}
	goldenText(t, "json.profile-file.json", buf.String())
	var doc struct {
		Files []struct {
			Guest, SHA256, Content string
			Bytes                  int
			Placeholders           []struct{ Text, Value string }
		}
	}
	if err := json.Unmarshal(buf.Bytes(), &doc); err != nil {
		t.Fatal(err)
	}
	if len(doc.Files) != 1 || doc.Files[0].Guest != "/home/u/.config/probe.conf" || len(doc.Files[0].SHA256) != 64 ||
		doc.Files[0].Bytes != len(doc.Files[0].Content) || len(doc.Files[0].Placeholders) != 1 {
		t.Errorf("files = %+v", doc.Files)
	}
}

