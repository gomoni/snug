func TestDryRunNeverPrintsGeneratedContent(t *testing.T) {
	p := probeFilePolicy(t, probeFileSelection()...)
	screen := dryRunText(p, []string{"/bin/sh"}, config{}, nil)
	files := blockBetween(t, screen, "FILES  (", "ENVIRONMENT")
	// Only the profile's own body appears under FILES; the generated
	// ~/.gitconfig the identity authors is a Secret and stays redacted.
	if strings.Contains(files, "gitconfig") || strings.Contains(files, "# Generated by snug") {
		t.Errorf("FILES block reaches a file snug generated:\n%s", files)
	}
	if strings.Contains(screen, "# Generated by snug") {
		t.Error("--dry-run printed the content of a file snug generated")
	}
}

