func TestProfileFileRowIsKindFileAndBareProvenance(t *testing.T) {
	p := probeFilePolicy(t, probeFileSelection()...)
	screen := dryRunText(p, []string{"/bin/sh"}, config{}, nil)
	fs := blockBetween(t, screen, "FILESYSTEM", "NOT GRANTED")
	var row string
	for _, l := range strings.Split(fs, "\n") {
		if strings.Contains(l, "/home/u/.config/probe.conf") {
			row = l
		}
	}
	if !strings.HasPrefix(strings.TrimSpace(row), "file ") || !strings.HasSuffix(row, " probefile") {
		t.Errorf("row = %q, want kind `file` and the bare profile name", row)
	}
}

