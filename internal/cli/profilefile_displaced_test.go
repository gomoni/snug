package cli

import (
	"bytes"
	"strings"
	"testing"

	"github.com/gomoni/snug/internal/policy"
)

// TestRefusedDryRunNeverPrintsADisplacedFilesGeneratedContent: a profile file
// at a path snug then generates (gh hosts.yml, @claude .credentials.json) is
// refused by Validate, but a refused document is still rendered. The ledger
// still names the guest while the mount there holds snug's Secret, so the
// FILES block and the JSON `files` array must print none of its bytes and
// must not present them as the profile's.
func TestRefusedDryRunNeverPrintsADisplacedFilesGeneratedContent(t *testing.T) {
	const guest = "/home/u/.config/gh/hosts.yml"
	const sentinel = "gho_SENTINELTOKEN"
	p := &policy.Policy{
		Mounts: map[string]policy.Mount{guest: {
			Guest: guest, Kind: policy.KindData, Access: policy.AccessRO, Authored: true,
			Content: policy.Secret("github.com:\n    oauth_token: " + sentinel + "\n"),
			From:    []string{"identity:id", "replaces:t"},
		}},
		Files: map[string]policy.ProfileFile{guest: {From: []policy.ProfileName{"t"}}},
	}
	files := buildFiles(p)
	if len(files) != 1 || !files[0].Displaced || files[0].Content != "" || files[0].SHA256 != "" {
		t.Fatalf("buildFiles = %+v, want one Displaced entry with no content", files)
	}

	var human bytes.Buffer
	describeFiles(&human, files)
	if strings.Contains(human.String(), sentinel) || strings.Contains(human.String(), "oauth_token") {
		t.Errorf("FILES block prints snug's generated bytes:\n%s", human.String())
	}
	if !strings.Contains(human.String(), "replaced by a file snug generates") {
		t.Errorf("FILES block does not say the profile's file was replaced:\n%s", human.String())
	}

	var js bytes.Buffer
	if err := renderJSON(&js, Report{Files: files}); err != nil {
		t.Fatal(err)
	}
	if strings.Contains(js.String(), sentinel) {
		t.Errorf("--dry-run --json prints snug's generated bytes:\n%s", js.String())
	}
	if !strings.Contains(js.String(), `"displaced": true`) && !strings.Contains(js.String(), `"displaced":true`) {
		t.Errorf("--dry-run --json does not mark the entry displaced:\n%s", js.String())
	}
}
