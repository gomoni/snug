// bookCommandLinePath is the user guide's page carrying `snug help`.
const bookCommandLinePath = "../../docs/src/reference/command-line.md"

// TestBookCommandLinePageIsGenerated renders docs/src/reference/command-line.md
// from writeUsage, the text `snug help` prints, and compares it with the
// committed page. The page is that text and nothing else, so the help and the
// book cannot disagree about a flag or a subcommand, and a change to either is
// a diff in the book. Regenerate with
//
//	go test ./internal/cli -run TestBookCommandLinePageIsGenerated -update
func TestBookCommandLinePageIsGenerated(t *testing.T) {
	var help strings.Builder
	writeUsage(&help)

	var b strings.Builder
	b.WriteString("<!-- GENERATED by TestBookCommandLinePageIsGenerated (internal/cli/bookcommandline_test.go)\n" +
		"     from `snug help`. Do not edit; regenerate with -update. -->\n\n")
	b.WriteString("# Command line\n\n")
	b.WriteString("The output of `snug help`.\n\n```text\n")
	b.WriteString(strings.TrimRight(help.String(), "\n"))
	b.WriteString("\n```\n")
	got := b.String()

	if *update {
		if err := os.WriteFile(bookCommandLinePath, []byte(got), 0o644); err != nil {
			t.Fatal(err)
		}
		return
	}
	want, err := os.ReadFile(bookCommandLinePath)
	if err != nil {
		t.Fatalf("%v\n  generate it: go test ./internal/cli -run TestBookCommandLinePageIsGenerated -update", err)
	}
	if string(want) != got {
		t.Errorf("%s is stale: `snug help` changed and the page did not.\n"+
			"  regenerate: go test ./internal/cli -run TestBookCommandLinePageIsGenerated -update",
			filepath.Clean(bookCommandLinePath))
	}
}

// TestUsageListsEveryFlagParseArgsAccepts reads parseArgs's source for every
// flag spelling it compares an argument with, and requires each in writeUsage.
// TestUsageListsEveryReservedWord holds the subcommands; this holds the flags,
// which have no table to range over, so the switch itself is the list. A flag
// parseArgs accepts and the help never names would be in neither `snug help`
// nor the book page above.
func TestUsageListsEveryFlagParseArgsAccepts(t *testing.T) {
	file, err := parser.ParseFile(token.NewFileSet(), "main.go", nil, 0)
	if err != nil {
		t.Fatal(err)
	}
	var body *ast.BlockStmt
	for _, d := range file.Decls {
		if fn, ok := d.(*ast.FuncDecl); ok && fn.Name.Name == "parseArgs" {
			body = fn.Body
		}
	}
	if body == nil {
		t.Fatal("main.go has no parseArgs: this test reads its switch for the flag spellings")
	}

	var flags []string
	ast.Inspect(body, func(n ast.Node) bool {
		var lit *ast.BasicLit
		switch e := n.(type) {
		case *ast.BinaryExpr:
			if e.Op == token.EQL {
				lit, _ = e.Y.(*ast.BasicLit)
			}
		case *ast.CallExpr:
			if sel, ok := e.Fun.(*ast.SelectorExpr); ok && sel.Sel.Name == "HasPrefix" && len(e.Args) == 2 {
				lit, _ = e.Args[1].(*ast.BasicLit)
			}
		}
		if lit == nil || lit.Kind != token.STRING {
			return true
		}
		s, err := strconv.Unquote(lit.Value)
		// "-" is the unknown-flag catch-all, not a flag.
		if err != nil || !strings.HasPrefix(s, "-") || s == "-" {
			return true
		}
		flags = append(flags, strings.TrimSuffix(s, "="))
		return true
	})
	slices.Sort(flags)
	flags = slices.Compact(flags)
	if len(flags) < 10 {
		t.Fatalf("found only %d flag spellings in parseArgs (%v): the source scan no longer matches how it compares arguments",
			len(flags), flags)
	}

	var help strings.Builder
	writeUsage(&help)
	for _, f := range flags {
		// A whole word, so "-p" is not found inside "--profile".
		named := regexp.MustCompile(`(^|[\s\[])` + regexp.QuoteMeta(f) + `($|[\s,\]])`)
		if !named.MatchString(help.String()) {
			t.Errorf("parseArgs accepts %q and usage() never names it: `snug help` and the book's command-line page omit a flag", f)
		}
	}
}
